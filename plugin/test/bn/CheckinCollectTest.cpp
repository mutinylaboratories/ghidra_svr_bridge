TEST_F(CheckinCollectTest, BookmarkAddAndDelete_Detected) {
    GhidraDbExport data;
    data.imageBase = kBase;
    GhidraBookmark bm;
    bm.type = "Note"; bm.addr = kBase + kOffDataInt;
    bm.category = "old"; bm.comment = "existing";
    data.bookmarks.push_back(bm);
    importAndStore(data);

    // Add a new tag …
    Ref<TagType> tt = view->GetTagType("Ghidra: Note");
    ASSERT_TRUE(tt);
    view->CreateUserDataTag(kBase + kOffDataStr, tt, "[fresh] added note", false);
    // … and delete the imported one.
    for (auto& tag : view->GetUserDataTags(kBase + kOffDataInt))
        view->RemoveUserDataTag(kBase + kOffDataInt, tag);

    GhidraCheckinPreview preview = collect();

    ASSERT_EQ(preview.bookmarkChanges.size(), 2u);
    const GhidraCheckinPreview::BookmarkChange* add = nullptr;
    const GhidraCheckinPreview::BookmarkChange* del = nullptr;
    for (const auto& b : preview.bookmarkChanges) {
        if (b.op == "add")    add = &b;
        if (b.op == "delete") del = &b;
    }
    ASSERT_TRUE(add);
    EXPECT_EQ(add->type, "Note");
    EXPECT_EQ(add->addr, kBase + kOffDataStr);
    EXPECT_EQ(add->category, "fresh");
    EXPECT_EQ(add->comment, "added note");
    ASSERT_TRUE(del);
    EXPECT_EQ(del->addr, kBase + kOffDataInt);
}

