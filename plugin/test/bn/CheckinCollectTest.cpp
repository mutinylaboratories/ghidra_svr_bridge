TEST_F(CheckinCollectTest, ParamRename_Detected) {
    Ref<Function> func = makeFunc(kBase + kOffFuncFrame);
    ASSERT_TRUE(func);
    auto params = func->GetParameterVariables().GetValue();
    if (params.empty())
        GTEST_SKIP() << "BN analysis found no parameters for frame function";

    GhidraDbExport data;
    data.imageBase = kBase;
    data.symbols.push_back(sym(20, "frame_func", kBase + kOffFuncFrame,
                               GhidraSymbolType::Function));
    GhidraParameter p;
    p.key      = 200;
    p.funcAddr = kBase + kOffFuncFrame;
    p.name     = "count";
    p.isParam  = true;
    p.ordinal  = 0;
    p.typeName = "int32_t";
    data.parameters.push_back(p);
    importAndStore(data);

    params = func->GetParameterVariables().GetValue();
    ASSERT_FALSE(params.empty());
    func->CreateUserVariable(params[0], func->GetVariableType(params[0]),
                             "renamed_count");
    GhidraCheckinPreview preview = collect();

    ASSERT_EQ(preview.paramRenames.size(), 1u);
    EXPECT_EQ(preview.paramRenames[0].key, 200);
    EXPECT_EQ(preview.paramRenames[0].name, "renamed_count");
}

// ---------------------------------------------------------------------------
// Preview stability across .bndb save/reopen
// ---------------------------------------------------------------------------

TEST_F(CheckinCollectTest, PreviewFromReopenedBndb_MatchesLivePreview) {
    GhidraDbExport data;
    data.imageBase = kBase;
    data.symbols.push_back(sym(42, "orig_func", kBase + kOffFuncRet,
                               GhidraSymbolType::Function));
    GhidraComment c;
    c.addr       = kBase + kOffFuncEquate;
    c.eol        = "imported";
    c.encodedKey = "0x2000000010";
    data.comments.push_back(c);
    importAndStore(data);

    // Pending edits the user made before closing BN.
    view->DefineUserSymbol(new Symbol(FunctionSymbol, "renamed_func",
                                      kBase + kOffFuncRet));
    view->SetCommentForAddress(kBase + kOffFuncEquate, "edited");

    GhidraCheckinPreview live = collect();
    ASSERT_EQ(live.renames.size(), 1u);
    ASSERT_EQ(live.comments.size(), 1u);

    std::string bndb = testDataDir() + "/tmp_checkin_persist.bndb";
    Ref<BinaryView> reopened = saveAndReopen(view, bndb);
    view = nullptr;
    ASSERT_TRUE(reopened);
    reopened->UpdateAnalysisAndWait();

    // Same singleton baseline (as after a BN restart with state restored):
    // the reopened database must yield the identical preview.
    GhidraCheckinPreview persisted =
        GhidraConnection::instance().collectCheckinChanges(reopened);
    ASSERT_EQ(persisted.renames.size(), 1u);
    EXPECT_EQ(persisted.renames[0].key, live.renames[0].key);
    EXPECT_EQ(persisted.renames[0].newName, live.renames[0].newName);
    ASSERT_EQ(persisted.comments.size(), 1u);
    EXPECT_EQ(persisted.comments[0].text, live.comments[0].text);
    EXPECT_EQ(persisted.comments[0].encodedKey, live.comments[0].encodedKey);

    closeView(reopened);
    std::remove(bndb.c_str());
}

