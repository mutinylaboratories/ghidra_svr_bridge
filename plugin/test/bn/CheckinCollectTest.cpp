constexpr uint64_t kBase = kDefaultBase;

class CheckinCollectTest : public ::testing::Test {
protected:
    void SetUp() override {
        BN_REQUIRE_CORE();
        view = makeView();
        ASSERT_TRUE(view);
    }
    void TearDown() override {
        GhidraConnection::instance().clearCheckinState();
        if (view) closeView(view);
    }

    Ref<Function> makeFunc(uint64_t va) {
        view->CreateUserFunction(view->GetDefaultPlatform(), va);
        view->UpdateAnalysisAndWait();
        for (auto& f : view->GetAnalysisFunctionsForAddress(va))
            if (f->GetStart() == va) return f;
        return nullptr;
    }

    // Import @p data into the view and seed the singleton's baseline maps —
    // the exact sequence the production import path runs.
    SyncResult importAndStore(const GhidraDbExport& data) {
        SyncResult r = SyncEngine::applyToView(view, data);
        view->UpdateAnalysisAndWait();
        GhidraConnection::instance().storeCheckinState(
            r.addrToKey, r.addrToOriginalName, r.addrToCommentKey,
            r.addrToOriginalComment, r.addrToOriginalFuncComment,
            r.addrToCommentField, r.ghidraDataTypes, r.parameters, r.bookmarks,
            r.dataItems, r.equates, r.funcSigs, r.imageBase,
            "testrepo", "/", "testitem");
        return r;
    }

    GhidraCheckinPreview collect() {
        view->UpdateAnalysisAndWait();
        return GhidraConnection::instance().collectCheckinChanges(view);
    }

    static GhidraSymbol sym(int64_t key, const std::string& name, uint64_t addr,
                            GhidraSymbolType type = GhidraSymbolType::Label) {
        GhidraSymbol s;
        s.key    = key;
        s.name   = name;
        s.addr   = addr;
        s.type   = type;
        s.source = GhidraSymbolSource::User;
        return s;
    }

    Ref<BinaryView> view;
};

