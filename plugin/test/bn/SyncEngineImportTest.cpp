TEST_F(SyncEngineImportTest, Symbols_LabelAndFunctionApplied) {
    GhidraDbExport data;
    data.imageBase = kBase;
    data.symbols.push_back(makeSymbol(1, "my_func", kBase + kOffFuncRet,
                                      GhidraSymbolType::Function));
    data.symbols.push_back(makeSymbol(2, "my_data", kBase + kOffDataInt));

    SyncResult r = apply(data);
    EXPECT_EQ(r.symbolsApplied, 2);
    EXPECT_EQ(r.functionsCreated, 1);

    auto funcSym = view->GetSymbolByAddress(kBase + kOffFuncRet);
    ASSERT_TRUE(funcSym);
    EXPECT_EQ(funcSym->GetShortName(), "my_func");
    EXPECT_EQ(funcSym->GetType(), FunctionSymbol);

    auto dataSym = view->GetSymbolByAddress(kBase + kOffDataInt);
    ASSERT_TRUE(dataSym);
    EXPECT_EQ(dataSym->GetShortName(), "my_data");

    // A real BN function was created for the Ghidra function symbol.
    bool hasFunc = false;
    for (auto& f : view->GetAnalysisFunctionsForAddress(kBase + kOffFuncRet))
        if (f->GetStart() == kBase + kOffFuncRet) hasFunc = true;
    EXPECT_TRUE(hasFunc);

    // Write-back baseline recorded.
    EXPECT_EQ(r.addrToKey.at(kBase + kOffFuncRet), 1);
    EXPECT_EQ(r.addrToOriginalName.at(kBase + kOffFuncRet), "my_func");
}

TEST_F(SyncEngineImportTest, Symbols_PreservesUserChosenName) {
    view->DefineUserSymbol(new Symbol(DataSymbol, "user_picked_this",
                                      kBase + kOffDataInt));

    GhidraDbExport data;
    data.imageBase = kBase;
    data.symbols.push_back(makeSymbol(7, "ghidra_name", kBase + kOffDataInt));
    SyncResult r = apply(data);

    auto sym = view->GetSymbolByAddress(kBase + kOffDataInt);
    ASSERT_TRUE(sym);
    EXPECT_EQ(sym->GetShortName(), "user_picked_this");
    // Ghidra's name is still the write-back baseline, so the user's name is
    // detected as a rename on the next check-in.
    EXPECT_EQ(r.addrToOriginalName.at(kBase + kOffDataInt), "ghidra_name");
}

