TEST_F(SyncEngineImportTest, MemoryBlocks_SectionForMappedAndSegmentForUnmapped) {
    GhidraDbExport data;
    data.imageBase = kBase;
    GhidraMemoryBlock mapped;
    mapped.name = ".gtext"; mapped.addr = kBase; mapped.size = 0x100;
    mapped.read = true; mapped.execute = true; mapped.initialized = true;
    data.memoryBlocks.push_back(mapped);
    GhidraMemoryBlock external;
    external.name = "EXTERNAL"; external.addr = kBase + 0x100000;
    external.size = 0x40; external.read = true; external.initialized = false;
    data.memoryBlocks.push_back(external);
    GhidraMemoryBlock overlay;
    overlay.name = "ovl"; overlay.addr = kBase; overlay.size = 0x10;
    overlay.overlay = true;
    data.memoryBlocks.push_back(overlay);

    SyncResult r = apply(data);
    EXPECT_EQ(r.sectionsAdded, 2);   // overlay skipped
    EXPECT_EQ(r.segmentsAdded, 1);   // only the unmapped EXTERNAL range

    bool foundText = false, foundExternal = false, foundOverlay = false;
    for (auto& sec : view->GetSections()) {
        if (sec->GetName() == ".gtext")   foundText = true;
        if (sec->GetName() == "EXTERNAL") foundExternal = true;
        if (sec->GetName() == "ovl")      foundOverlay = true;
    }
    EXPECT_TRUE(foundText);
    EXPECT_TRUE(foundExternal);
    EXPECT_FALSE(foundOverlay);
    EXPECT_TRUE(view->GetSegmentAt(kBase + 0x100000));
}

