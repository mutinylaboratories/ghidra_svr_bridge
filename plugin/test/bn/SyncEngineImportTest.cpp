TEST_F(SyncEngineImportTest, FuncSigs_ReturnTypeAppliedAndCcAccepted) {
    Ref<Function> func = makeFunc(kBase + kOffFuncRet);
    ASSERT_TRUE(func);

    std::string curCC;
    {
        auto cc = func->GetCallingConvention();
        if (cc.GetValue()) curCC = cc.GetValue()->GetName();
    }

    GhidraDbExport data;
    data.imageBase = kBase;
    data.symbols.push_back(makeSymbol(10, "sig_func", kBase + kOffFuncRet,
                                      GhidraSymbolType::Function));
    GhidraFuncSig sig;
    sig.key = 10;
    // CC import is applied at "imported" confidence (128), which BN's own
    // confident platform default outranks — so an alternate CC is NOT
    // guaranteed to stick. Import the current CC name (must be a clean no-op)
    // and pin the return type, which does apply.
    sig.callingConvention = curCC;
    sig.returnTypeName    = "longlong";
    data.funcSigs.push_back(sig);
    apply(data);

    auto ret = func->GetReturnType();
    ASSERT_TRUE(ret.GetValue());
    EXPECT_EQ(ret.GetValue()->GetWidth(), 8u); // longlong → int64_t
    if (!curCC.empty()) {
        auto cc = func->GetCallingConvention();
        ASSERT_TRUE(cc.GetValue());
        EXPECT_EQ(cc.GetValue()->GetName(), curCC);
    }
}

