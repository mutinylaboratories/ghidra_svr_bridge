TEST_F(SyncEngineImportTest, FuncFlags_BecomeTags) {
    GhidraDbExport data;
    data.imageBase = kBase;
    data.symbols.push_back(makeSymbol(10, "thunk_func", kBase + kOffFuncThunk,
                                      GhidraSymbolType::Function));
    data.symbols.push_back(makeSymbol(11, "noret_func", kBase + kOffFuncNoRet,
                                      GhidraSymbolType::Function));
    GhidraFuncFlags f1; f1.key = 10; f1.thunk = true;
    GhidraFuncFlags f2; f2.key = 11; f2.noReturn = true; f2.isInline = true;
    data.funcFlags = {f1, f2};

    SyncResult r = apply(data);
    EXPECT_EQ(r.flagsApplied, 2);

    auto tagsAt = [&](uint64_t va) {
        std::vector<std::string> names;
        for (auto& f : view->GetAnalysisFunctionsForAddress(va)) {
            if (f->GetStart() != va) continue;
            for (auto& t : f->GetFunctionTags())
                names.push_back(t->GetType()->GetName());
        }
        return names;
    };
    auto thunkTags = tagsAt(kBase + kOffFuncThunk);
    EXPECT_NE(std::find(thunkTags.begin(), thunkTags.end(),
                        std::string("Ghidra: Thunk")), thunkTags.end());
    auto noretTags = tagsAt(kBase + kOffFuncNoRet);
    EXPECT_NE(std::find(noretTags.begin(), noretTags.end(),
                        std::string("Ghidra: NoReturn")), noretTags.end());
    EXPECT_NE(std::find(noretTags.begin(), noretTags.end(),
                        std::string("Ghidra: Inline")), noretTags.end());
}

