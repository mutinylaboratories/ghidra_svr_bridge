constexpr uint64_t kBase = kDefaultBase;

GhidraSymbol makeSymbol(int64_t key, const std::string& name, uint64_t addr,
                        GhidraSymbolType type = GhidraSymbolType::Label) {
    GhidraSymbol s;
    s.key    = key;
    s.name   = name;
    s.addr   = addr;
    s.type   = type;
    s.source = GhidraSymbolSource::User;
    return s;
}

class SyncEngineImportTest : public ::testing::Test {
protected:
    void SetUp() override {
        BN_REQUIRE_CORE();
        view = makeView();
        ASSERT_TRUE(view);
    }
    void TearDown() override {
        if (view) closeView(view);
    }

    // Create a function and wait for analysis so parameter variables and
    // function extents exist before the import runs (mirrors a real session,
    // where BN has analyzed the binary before the user imports).
    Ref<Function> makeFunc(uint64_t va) {
        view->CreateUserFunction(view->GetDefaultPlatform(), va);
        view->UpdateAnalysisAndWait();
        for (auto& f : view->GetAnalysisFunctionsForAddress(va))
            if (f->GetStart() == va) return f;
        return nullptr;
    }

    SyncResult apply(const GhidraDbExport& data) {
        SyncResult r = SyncEngine::applyToView(view, data);
        view->UpdateAnalysisAndWait();
        return r;
    }

    Ref<BinaryView> view;
};

