TEST_F(SyncEngineImportTest, Bndb_ImportedStateSurvivesSaveReopen) {
    Ref<Function> func = makeFunc(kBase + kOffFuncEquate);
    ASSERT_TRUE(func);

    GhidraDbExport data;
    data.imageBase = kBase;
    data.symbols.push_back(makeSymbol(1, "persisted_func", kBase + kOffFuncEquate,
                                      GhidraSymbolType::Function));
    GhidraComment c;
    c.addr = kBase + kOffFuncEquate;
    c.eol  = "persisted comment";
    data.comments.push_back(c);
    GhidraDataType dt;
    dt.id = 100; dt.kind = "struct"; dt.name = "Persisted"; dt.size = 4;
    dt.members.push_back({0, 0, "v", "", 4, 0, "int"});
    data.dataTypes.push_back(dt);
    GhidraDataItem item;
    item.addr = kBase + kOffDataPoint;
    item.typeId = 100;
    data.dataItems.push_back(item);
    GhidraBookmark bm;
    bm.type = "Note"; bm.addr = kBase + kOffDataStr;
    bm.category = "cat"; bm.comment = "bm";
    data.bookmarks.push_back(bm);
    apply(data);

    std::string bndb = testDataDir() + "/tmp_import_persist.bndb";
    Ref<BinaryView> reopened = saveAndReopen(view, bndb);
    view = nullptr; // original closed by saveAndReopen
    ASSERT_TRUE(reopened);

    auto sym = reopened->GetSymbolByAddress(kBase + kOffFuncEquate);
    ASSERT_TRUE(sym);
    EXPECT_EQ(sym->GetShortName(), "persisted_func");
    EXPECT_EQ(reopened->GetCommentForAddress(kBase + kOffFuncEquate),
              "persisted comment");
    Ref<Type> t = reopened->GetTypeByName(QualifiedName("Persisted"));
    ASSERT_TRUE(t);
    EXPECT_TRUE(t->IsStructure());
    auto dataVars = reopened->GetDataVariables();
    EXPECT_NE(dataVars.find(kBase + kOffDataPoint), dataVars.end());
    auto tags = reopened->GetUserDataTags(kBase + kOffDataStr);
    ASSERT_EQ(tags.size(), 1u);
    EXPECT_EQ(tags[0]->GetData(), "[cat] bm");

    closeView(reopened);
    std::remove(bndb.c_str());
}

